-- 007_add_cash_transaction_reasons.sql
-- Creates a branch-scoped cash_transaction_reasons lookup table so each
-- branch can define its own cash-in / cash-out reasons dynamically.
-- Seeds 8 default reasons for all existing branches.
-- Changes shift_cash_transactions.reason from PostgreSQL enum to text.

CREATE TABLE cash_transaction_reasons (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  branch_id INTEGER NOT NULL REFERENCES branches(id),
  key TEXT NOT NULL,
  label TEXT NOT NULL,
  type cash_transaction_type,
  is_active BOOLEAN NOT NULL DEFAULT true,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT now(),
  updated_at TIMESTAMP NOT NULL DEFAULT now(),
  UNIQUE(branch_id, key)
);

CREATE INDEX ON cash_transaction_reasons (branch_id, is_active, sort_order);

INSERT INTO cash_transaction_reasons (branch_id, key, label, type, is_active, sort_order)
SELECT b.id, v.key, v.label, v.type::cash_transaction_type, true, v.sort_order
FROM branches b
CROSS JOIN (VALUES
  ('gaji',               'Gaji',               'cash_out', 1),
  ('pengeluaran_pribadi','Pengeluaran Pribadi', 'cash_out', 2),
  ('supply_purchase',    'Supply Purchase',     'cash_out', 3),
  ('petty_cash',         'Petty Cash',          'cash_out', 4),
  ('angsuran',           'Angsuran',            'cash_in',  5),
  ('cash_deposit',       'Cash Deposit',        'cash_in',  6),
  ('operasional',        'Operasional',         'cash_out', 7),
  ('other',              'Other',               NULL,       8)
) AS v(key, label, type, sort_order);

ALTER TABLE shift_cash_transactions ALTER COLUMN reason TYPE text;
